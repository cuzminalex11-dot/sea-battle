"""
ship.py — модель одного корабля.

Корабль знает свои клетки и считает попадания в себя.
Логика того, как корабли размещаются на поле, живёт в board.py.
"""

# Ориентация корабля: по горизонтали или по вертикали.
# Строки, а не числа — чтобы в коде читалось понятно.


class Ship:
    def __init__(self, cells: list[tuple[int, int]]):
        """
        cells — список координат клеток корабля, например:
        [(2, 3), (2, 4), (2, 5)] — трёхпалубник вертикальный.

        Список кортежей удобен тем, что его легко проверить:
        «есть ли клетка (2, 4) в этом корабле» — обычный оператор in.
        """
        if not cells:
            raise ValueError("Корабль не может быть пустым")
        self.cells = list(cells)   # копия, чтобы извне не изменили наш список
        self.hits = 0              # сколько попаданий получил

    @property
    def size(self) -> int:
        """Размер корабля = количество его клеток."""
        return len(self.cells)

    @property
    def is_sunk(self) -> bool:
        """Корабль потоплен, если все его клетки подбиты."""
        return self.hits >= self.size

    def register_hit(self, x: int, y: int) -> bool:
        """
        Регистрирует попадание, если выстрел пришёлся по этому кораблю.
        Возвращает True, если попали, и False, если мимо.
        """
        if (x, y) in self.cells:
            self.hits += 1
            return True
        return False

    def get_cells(self) -> list[tuple[int, int]]:
        """Возвращает копию списка клеток — для отправки по сети в поле cells."""
        return list(self.cells)
